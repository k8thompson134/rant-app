import { useRef, useState } from 'react';
import { RantEntry } from '../types';

function download(name: string, mime: string, body: string) {
  const url = URL.createObjectURL(new Blob([body], { type: mime }));
  const a = document.createElement('a');
  a.href = url; a.download = name; a.click();
  URL.revokeObjectURL(url);
}

const csvCell = (v: string) => `"${v.replace(/"/g, '""')}"`;

export default function Data({ entries, onReplace }: { entries: RantEntry[]; onReplace: (e: RantEntry[]) => void }) {
  const file = useRef<HTMLInputElement>(null);
  const [msg, setMsg] = useState('');
  const [confirming, setConfirming] = useState(false);

  const importFile = async (f: File) => {
    try {
      const parsed = JSON.parse(await f.text());
      if (!Array.isArray(parsed) || !parsed.every((e) => e && typeof e.id === 'string' && typeof e.text === 'string' && typeof e.timestamp === 'number' && Array.isArray(e.symptoms))) {
        throw new Error('not a RantTrack export');
      }
      const known = new Set(entries.map((e) => e.id));
      const fresh = (parsed as RantEntry[]).filter((e) => !known.has(e.id));
      onReplace([...fresh, ...entries].sort((a, b) => b.timestamp - a.timestamp));
      setMsg(`Imported ${fresh.length} new entries.`);
    } catch (e) {
      setMsg(`Import failed: ${String(e)}`);
    }
  };

  const exportCsv = () => {
    const rows = entries.map((e) => [new Date(e.timestamp).toISOString(), csvCell(e.symptoms.map((s) => s.symptom).join('; ')), csvCell(e.text)].join(','));
    download('ranttrack.csv', 'text/csv', ['timestamp,symptoms,text', ...rows].join('\n'));
  };

  const exportReport = () => {
    if (!entries.length) return;
    const range = `${new Date(entries[entries.length - 1].timestamp).toLocaleDateString()} – ${new Date(entries[0].timestamp).toLocaleDateString()}`;

    const symptomCounts = new Map<string, number>();
    const triggerCounts = new Map<string, number>();
    const severities: string[] = [];

    for (const e of entries) {
      for (const s of e.symptoms) {
        const name = s.symptom.replace(/_/g, ' ');
        symptomCounts.set(name, (symptomCounts.get(name) ?? 0) + 1);
        if (s.severity) severities.push(s.severity);
        if (s.trigger?.activity) {
          triggerCounts.set(s.trigger.activity, (triggerCounts.get(s.trigger.activity) ?? 0) + 1);
        }
      }
    }

    const topSymptoms = [...symptomCounts].sort((a, b) => b[1] - a[1]).slice(0, 10);
    const topTriggers = [...triggerCounts].sort((a, b) => b[1] - a[1]).slice(0, 5);

    const mildCount = severities.filter(s => s === 'mild').length;
    const modCount = severities.filter(s => s === 'moderate').length;
    const sevCount = severities.filter(s => s === 'severe').length;

    let report = `SYMPTOM REPORT\nGenerated: ${new Date().toLocaleDateString()}\nPeriod: ${range}\nEntries: ${entries.length}\n\n`;
    report += `SEVERITY BREAKDOWN\n  Mild: ${mildCount}  |  Moderate: ${modCount}  |  Severe: ${sevCount}\n\n`;
    report += `TOP SYMPTOMS\n`;
    for (const [name, count] of topSymptoms) {
      report += `  ${name}: ${count} occurrence${count !== 1 ? 's' : ''}\n`;
    }
    if (topTriggers.length) {
      report += `\nCOMMON TRIGGERS\n`;
      for (const [name, count] of topTriggers) {
        report += `  ${name}: ${count} time${count !== 1 ? 's' : ''}\n`;
      }
    }
    report += `\n---\nGenerated by RantTrack. Data is self-reported.\n`;

    download('ranttrack-report.txt', 'text/plain', report);
  };

  return (
    <section>
      <p>{entries.length} entries stored in this browser. Nothing is sent anywhere.</p>
      <div className="row">
        <button onClick={() => download('ranttrack.json', 'application/json', JSON.stringify(entries, null, 2))} disabled={!entries.length}>Export JSON</button>
        <button onClick={exportCsv} disabled={!entries.length}>Export CSV</button>
        <button onClick={exportReport} disabled={!entries.length}>Doctor report</button>
        <button onClick={() => file.current?.click()}>Import JSON</button>
        <input ref={file} type="file" accept="application/json" hidden onChange={(e) => e.target.files?.[0] && importFile(e.target.files[0])} />
      </div>
      {msg && <p role="status">{msg}</p>}
      {confirming ? (
        <div className="row" role="alert">
          <span>Delete all {entries.length} entries from this browser? Export first if you might want them.</span>
          <button className="danger-solid" onClick={() => { onReplace([]); setConfirming(false); }}>Yes, delete all</button>
          <button onClick={() => setConfirming(false)}>Cancel</button>
        </div>
      ) : (
        <button className="danger" disabled={!entries.length} onClick={() => setConfirming(true)}>Delete all entries</button>
      )}
    </section>
  );
}
